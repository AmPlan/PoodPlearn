export const namingCatalog: CatalogSet[] = definitions.map(
	([level, levelName, category, number, folder, rows]) => {
		const id = `${level}-${number}`;
		return {
			id,
			number,
			level,
			levelName,
			category,
			questions: rows
				.trim()
				.split("\n")
				.map((row, index) => {
					const [answer, stem, featureHint] = row.trim().split("|");
					const missingAudio = stem === "towel";
					return {
						id: `${id}-${index + 1}`,
						answer,
						featureHint,
						initialHint: "รอคำใบ้พยางค์แรก",
						imageSrc: `/training_images/${folder}/${stem}.png`,
						answerAudioSrc: missingAudio
							? undefined
							: `/training_sounds/${folder}/${stem}.wav`,
					};
				}),
		};
	},
);

export const NAMING_PROMPT_AUDIO = "/training_sounds/Naming_Question.wav";
export const findCatalogSet = (id: string) =>
	namingCatalog.find((set) => set.id === id);
export const missingImages = (set: CatalogSet) =>
	set.questions.filter((question) => !question.imageSrc);
export const isSetReady = (set: CatalogSet) =>
	set.questions.length === 15 && missingImages(set).length === 0;
